// Convert all coordinates
function convertMultiPolygon(multiPolygon) {
  return multiPolygon.map(polygon =>
    polygon.map(ring =>
      ring.map(coord => {
        const [lat, lng] = bngToLatLng(coord[0], coord[1]);
        return [lat, lng];
      })
    )
  );
}

